"""Build evals/reports/results.md from recorded runs. Experiments without a run say so.

uv run python -m evals.report
"""

from __future__ import annotations

import json
import math
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).parent
RUNS_DIR = ROOT / "reports" / "runs"
OUT = ROOT / "reports" / "results.md"
EXPERIMENTS = [
    ("E0", "Single ReAct agent, all tools"),
    ("E1", "Supervisor + SQL/Knowledge specialists"),
    ("E2", "E1 + verifier"),
    ("E3", "E1 + parallel fan-out"),
]
NOT_MEASURED = "not yet measured"


def percentile(values: list[float], q: float) -> float:
    if not values:
        return math.nan
    s = sorted(values)
    k = (len(s) - 1) * q
    lo, hi = math.floor(k), math.ceil(k)
    return s[lo] + (s[hi] - s[lo]) * (k - lo)


def latest_runs(runs_dir: Path = RUNS_DIR) -> dict[str, dict[str, Any]]:
    latest: dict[str, dict[str, Any]] = {}
    for path in sorted(runs_dir.glob("*.json")) if runs_dir.exists() else []:
        run = json.loads(path.read_text("utf-8"))
        cur = latest.get(run["experiment"])
        if cur is None or run["timestamp"] >= cur["timestamp"]:
            latest[run["experiment"]] = {**run, "_file": path.name}
    return latest


def _mean(xs: list[float]) -> float:
    return sum(xs) / len(xs) if xs else math.nan


def summarize(run: dict[str, Any]) -> dict[str, Any]:
    recs = run["records"]
    by_repeat: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for r in recs:
        by_repeat[r["repeat"]].append(r)
    acc_per_repeat = [_mean([float(r["correct"]) for r in rs]) for rs in by_repeat.values()]
    held = [float(r["correct"]) for r in recs if r["held_out"]]
    by_diff = {
        d: _mean([float(r["correct"]) for r in recs if r["difficulty"] == d])
        for d in ("easy", "medium", "hard")
    }
    with_numbers = [
        r["scores"]["numeric_groundedness"] for r in recs if r["scores"].get("answer_has_numbers")
    ]
    lat = [r["latency_s"] for r in recs]
    failures = Counter(r["failure"] for r in recs if r["failure"])
    examples: dict[str, list[str]] = defaultdict(list)
    for r in recs:
        if r["failure"] and r["id"] not in examples[r["failure"]]:
            examples[r["failure"]].append(r["id"])
    return {
        "n_questions": len({r["id"] for r in recs}),
        "repeats": len(by_repeat),
        "acc_mean": _mean(acc_per_repeat),
        "acc_min": min(acc_per_repeat, default=math.nan),
        "acc_max": max(acc_per_repeat, default=math.nan),
        "held_out_acc": _mean(held),
        "by_difficulty": by_diff,
        "groundedness": _mean(with_numbers),
        "n_grounded_checked": len(with_numbers),
        "p50": percentile(lat, 0.5),
        "p95": percentile(lat, 0.95),
        "tokens_in": _mean([r["tokens"]["input"] for r in recs]),
        "tokens_out": _mean([r["tokens"]["output"] for r in recs]),
        "failures": failures.most_common(5),
        "failure_examples": {k: v[:3] for k, v in examples.items()},
    }


def _pct(x: float) -> str:
    return NOT_MEASURED if math.isnan(x) else f"{x:.1%}"


def render(runs: dict[str, dict[str, Any]]) -> str:
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python -m evals.report` from `evals/reports/runs/*.json`. "
        "A cell says `not yet measured` when no run exists. Cost per request is not computed "
        "because model prices have not been verified; token counts are shown instead.",
        "",
        "| Experiment | Design | Runs (questions x repeats) | SQL exec acc, mean [range] | "
        "Held-out acc | Groundedness | Anomaly recall | Safety pass | p50 / p95 latency | "
        "Tokens in / out per request |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    details: list[str] = []
    for exp, design in EXPERIMENTS:
        run = runs.get(exp)
        if run is None:
            lines.append(
                f"| {exp} | {design} | {NOT_MEASURED} | {NOT_MEASURED} | {NOT_MEASURED} | "
                f"{NOT_MEASURED} | {NOT_MEASURED} | {NOT_MEASURED} | {NOT_MEASURED} | "
                f"{NOT_MEASURED} |"
            )
            continue
        s = summarize(run)
        lines.append(
            f"| {exp} | {design} | {s['n_questions']} x {s['repeats']} | "
            f"{_pct(s['acc_mean'])} [{_pct(s['acc_min'])} to {_pct(s['acc_max'])}] | "
            f"{_pct(s['held_out_acc'])} | {_pct(s['groundedness'])} "
            f"(n={s['n_grounded_checked']}) | {NOT_MEASURED} | {NOT_MEASURED} | "
            f"{s['p50']:.1f}s / {s['p95']:.1f}s | {s['tokens_in']:.0f} / {s['tokens_out']:.0f} |"
        )
        details += [
            f"## {exp} details",
            "",
            f"- Source: `{run['_file']}`; git `{run['git_sha']}`; models `{run['model_ids']}`; "
            f"prompt versions `{run['prompt_versions']}`.",
            "- Accuracy by difficulty: "
            + ", ".join(f"{d} {_pct(v)}" for d, v in s["by_difficulty"].items()),
            "- Top failure categories (count across repeats; example question ids): "
            + (
                "; ".join(
                    f"{k} x{n} ({', '.join(s['failure_examples'][k])})" for k, n in s["failures"]
                )
                or "none"
            ),
            "",
        ]
    lines += [
        "",
        "Interpretation limits: the gold set is small and synthetic; with 31 questions a "
        "difference of a few points is within noise (one question = 3.2 points). Groundedness "
        "is a rule-based numeric check over answers that contain numbers.",
        "",
    ]
    return "\n".join(lines + details)


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(latest_runs()), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
